  // ==========================================================================
  // [동적 파츠 레지스트리 (Dynamic Parts Registry)]
  // JSON 파일이 추가되면 자동으로 등록 및 렌더링을 지원하는 범용 엔진
  // ==========================================================================
  const DYNAMIC_PARTS = {
    face: {}, hair: {}, outfit: {}, bottom: {}, acc: {}
  };

  function registerDynamicPart(category, partKey, data) {
    if (!DYNAMIC_PARTS[category]) DYNAMIC_PARTS[category] = {};
    const meta = data.meta || {};
    const ox = typeof meta.x === 'number' ? meta.x : (typeof meta.offsetX === 'number' ? meta.offsetX : 0);
    const oy = typeof meta.y === 'number' ? meta.y : (typeof meta.offsetY === 'number' ? meta.offsetY : 0);

    const prev = DYNAMIC_PARTS[category][partKey];
    const currentOffset = prev ? prev.offset : { x: ox, y: oy };

    DYNAMIC_PARTS[category][partKey] = {
      meta: meta,
      palette: Array.isArray(data.palette) ? [...data.palette] : [],
      pixels: Array.isArray(data.pixels) ? [...data.pixels] : [],
      offset: currentOffset
    };

    if (category === 'face') {
      FACE[partKey] = (eyeColor) => renderDynamicPart('face', partKey, eyeColor);
    } else if (category === 'hair') {
      HAIR[partKey] = (hairColor) => renderDynamicPart('hair', partKey, hairColor);
    } else if (category === 'outfit') {
      OUTFIT[partKey] = () => renderDynamicPart('outfit', partKey);
    } else if (category === 'bottom') {
      BOTTOM[partKey] = () => renderDynamicPart('bottom', partKey);
    } else if (category === 'acc') {
      ACC[partKey] = () => renderDynamicPart('acc', partKey);
    }
  }

  function renderDynamicPart(category, partKey, color) {
    const entry = DYNAMIC_PARTS[category] && DYNAMIC_PARTS[category][partKey];
    if (!entry || !entry.pixels.length) return '';

    let pal = [...entry.palette];
    if (category === 'face' && color) {
      const e = getEyeTones(color);
      if (e.dark && pal[41]) pal[41] = e.dark;
      if (e.main && pal[42]) pal[42] = e.main;
      if (e.light && pal[45]) pal[45] = e.light;
    } else if (category === 'hair' && color) {
      const h = getHairTones(color);
      if (pal.length > 1) pal[1] = h.base;
    }

    const ox = entry.offset.x;
    const oy = entry.offset.y;
    const byColorAndRow = {};

    for (let i = 0; i < entry.pixels.length; i++) {
      const [px, py, cIdx] = entry.pixels[i];
      const col = pal[cIdx] || (typeof cIdx === 'string' ? cIdx : '#000000');
      const y = py + oy;
      const x = px + ox;
      if (!byColorAndRow[col]) byColorAndRow[col] = {};
      if (!byColorAndRow[col][y]) byColorAndRow[col][y] = [];
      byColorAndRow[col][y].push(x);
    }

    const spansMap = {};
    for (const col in byColorAndRow) {
      spansMap[col] = [];
      const rows = byColorAndRow[col];
      for (const yStr in rows) {
        const y = parseInt(yStr, 10);
        const xs = rows[yStr].sort((a, b) => a - b);
        let startX = xs[0];
        let len = 1;
        for (let k = 1; k < xs.length; k++) {
          if (xs[k] === startX + len) {
            len++;
          } else {
            spansMap[col].push([startX, y, len]);
            startX = xs[k];
            len = 1;
          }
        }
        spansMap[col].push([startX, y, len]);
      }
    }
    return spansToSVG(spansMap);
  }

  /**
   * 지정된 파츠를 43x68 픽셀 뷰포트 규격으로 렌더링
   * @param {string} category - hair, face, outfit, bottom, acc
   * @param {string} partKey - H01, F01, O01, etc.
   * @param {string} color - hairColor, eyeColor 등
   */
  function renderPart(category, partKey, color) {
    const table = { hair: HAIR, face: FACE, outfit: OUTFIT, bottom: BOTTOM, acc: ACC }[category];
    if (!table) return '';
    let fn = table[partKey];
    if (!fn && DYNAMIC_PARTS[category] && DYNAMIC_PARTS[category][partKey]) {
      fn = (c) => renderDynamicPart(category, partKey, c);
    }
    if (!fn) fn = table[Object.keys(table)[0]];
    if (!fn) return '';
    const content = fn(color);
    if (!content) return '';
    return `<g class="pixel-part-${category} part-${partKey}" shape-rendering="crispEdges">${content}</g>`;
  }

  return {
    hair: HAIR,
    face: FACE,
    outfit: OUTFIT,
    bottom: BOTTOM,
    acc: ACC,
    dynamicParts: DYNAMIC_PARTS,
    registerPart: registerDynamicPart,
    render: renderPart,
    getHairTones: getHairTones,
    getEyeTones: getEyeTones,
    setOffset: (category, partKey, x, y) => {
      if (category === 'face') {
        if (partKey === 'F07') {
          if (typeof x === 'number') F07_OFFSET.x = x;
          if (typeof y === 'number') F07_OFFSET.y = y;
        } else if (partKey === 'F08') {
          if (typeof x === 'number') F08_OFFSET.x = x;
          if (typeof y === 'number') F08_OFFSET.y = y;
        } else if (partKey === 'F09') {
          if (typeof x === 'number') F09_OFFSET.x = x;
          if (typeof y === 'number') F09_OFFSET.y = y;
        } else if (DYNAMIC_PARTS[category] && DYNAMIC_PARTS[category][partKey]) {
          if (typeof x === 'number') DYNAMIC_PARTS[category][partKey].offset.x = x;
          if (typeof y === 'number') DYNAMIC_PARTS[category][partKey].offset.y = y;
        }
      } else if (DYNAMIC_PARTS[category] && DYNAMIC_PARTS[category][partKey]) {
        if (typeof x === 'number') DYNAMIC_PARTS[category][partKey].offset.x = x;
        if (typeof y === 'number') DYNAMIC_PARTS[category][partKey].offset.y = y;
      }
    },
    getOffset: (category, partKey) => {
      if (category === 'face') {
        if (partKey === 'F07') return { ...F07_OFFSET };
        if (partKey === 'F08') return { ...F08_OFFSET };
        if (partKey === 'F09') return { ...F09_OFFSET };
        if (DYNAMIC_PARTS[category] && DYNAMIC_PARTS[category][partKey]) {
          return { ...DYNAMIC_PARTS[category][partKey].offset };
        }
      } else if (DYNAMIC_PARTS[category] && DYNAMIC_PARTS[category][partKey]) {
        return { ...DYNAMIC_PARTS[category][partKey].offset };
      }
      return { x: 0, y: 0 };
    }
  };
